import "server-only";
import { createHash, createHmac, timingSafeEqual } from "node:crypto";
import { mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { ObjectTooLargeError, type ObjectStorage } from "./types";

/**
 * Local-disk storage for development and end-to-end tests, so they need no cloud account.
 * The browser uploads to /api/uploads/local with an HMAC-signed link that mimics an R2 presigned URL.
 * Never used on a deployed site (see getStorage()).
 */

const ROOT = path.join(process.cwd(), ".data", "storage");
const UPLOAD_URL_TTL_MS = 5 * 60 * 1000;
// Without UPLOAD_SIGNING_SECRET, derive a stable secret. It must be the same in every server
// bundle (server actions and route handlers load this module separately), so it can't be random.
// Local storage only ever runs on a developer machine or in CI.
const processSecret = createHash("sha256")
  .update(`local-upload-signing:${process.env.DATABASE_URL ?? ""}:${process.cwd()}`)
  .digest("hex");

/** Keys are generated by the server, but check anyway so a key can never escape the storage root. */
export function isSafeKey(key: string): boolean {
  return /^(incoming|listings)\/[a-zA-Z0-9/_-]+(\.[a-z0-9]+)?$/.test(key) && !key.includes("..");
}

function resolve(key: string) {
  if (!isSafeKey(key)) throw new Error("Invalid storage key");
  return path.join(ROOT, key);
}

export type LocalUploadClaims = { key: string; contentType: string; contentLength: number; expires: number };

function sign(secret: string, claims: LocalUploadClaims) {
  return createHmac("sha256", secret)
    .update(`${claims.key}\n${claims.contentType}\n${claims.contentLength}\n${claims.expires}`)
    .digest("hex");
}

export function verifyLocalUpload(secret: string | undefined, claims: LocalUploadClaims, signature: string): boolean {
  if (!isSafeKey(claims.key) || !claims.key.startsWith("incoming/")) return false;
  if (!Number.isFinite(claims.expires) || claims.expires < Date.now()) return false;
  const expected = Buffer.from(sign(secret ?? processSecret, claims));
  const given = Buffer.from(signature);
  return expected.length === given.length && timingSafeEqual(expected, given);
}

export function createLocalStorage(secret: string | undefined): ObjectStorage {
  return {
    name: "local",
    async createUploadUrl({ key, contentType, contentLength }) {
      const claims = { key, contentType, contentLength, expires: Date.now() + UPLOAD_URL_TTL_MS };
      const params = new URLSearchParams({
        key,
        type: contentType,
        length: String(contentLength),
        expires: String(claims.expires),
        signature: sign(secret ?? processSecret, claims),
      });
      return { url: `/api/uploads/local?${params}`, headers: { "Content-Type": contentType } };
    },
    async getObject(key, maxBytes) {
      const file = resolve(key);
      try {
        if ((await stat(file)).size > maxBytes) throw new ObjectTooLargeError();
        return await readFile(file);
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code === "ENOENT") return null;
        throw error;
      }
    },
    async putObject(key, body) {
      const file = resolve(key);
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, body);
    },
    async deleteObjects(keys) {
      await Promise.all(keys.map((key) => rm(resolve(key), { force: true })));
    },
    publicUrl: (key) => `/api/uploads/file/${key}`,
  };
}
